NAMES = ('initial', 'local', 'mixed')


def rows(path):
    return [json.loads(line) for line in path.read_text().splitlines()]


def values(row):
    return dict(lpips=row['quality']['lpips_alex'], psnr=row['quality']['psnr_db'],
                phase=row['phase_error']['phase_rms_u8'],
                temporal_mae=row['quality']['temporal_delta_mae'])


def compare_cases(cases):
    """Same-sample, SAME inference view; never confuse FOV gain with training gain."""
    result = []
    for item in cases:
        indexed = {(r['name'], r['size']): r for r in item['results']}
        if len(indexed) != 6 or set(indexed) != {(n,s) for n in NAMES for s in (256,512)}:
            raise ValueError('missing or duplicate paired endpoint')
        for size in (256,512):
            initial, local, mixed = (values(indexed[n,size]) for n in NAMES)
            result.append(dict(sample=item['case']['sample_id'], dataset=item['case']['dataset'],
                group=item['case']['evaluation_group'], size=size,
                initial=initial, local=local, mixed=mixed,
                mixed_minus_local={k:mixed[k]-local[k] for k in mixed},
                mixed_minus_initial={k:mixed[k]-initial[k] for k in mixed}))
    return result


def grouped(pairs):
    groups = defaultdict(list)
    for row in pairs: groups[row['group'],row['dataset'],row['size']].append(row)
    output = []
    for (group,dataset,size), items in sorted(groups.items()):
        record = dict(group=group,dataset=dataset,size=size,count=len(items))
        for name in (*NAMES,'mixed_minus_local','mixed_minus_initial'):
            record[name] = {k:float(np.mean([i[name][k] for i in items])) for k in items[0][name]}
        record['mixed_better_than_local'] = {
            k:sum(i['mixed_minus_local'][k]*(1 if k=='psnr' else -1)>0 for i in items)
            for k in items[0]['initial']}
        output.append(record)
    return output


def audit(root):
    done = read(root/'complete.json')
    if not done['complete'] or done['production_changed']: raise ValueError('not a frozen completed run')
    verify_artifacts(root,done['artifacts'])
    verify_probe(root.parent/'probe')
    cfg = read(root/'formal/protocol.json')
    for name,sha in cfg['code'].items():
        if digest(REPO/name)!=sha: raise ValueError('pinned source changed: '+name)
    for spec in (*cfg['assets'].values(),cfg['initial']):
        if digest(spec['path'])!=spec['sha256']: raise ValueError('bound model changed')
    initial = torch.load(cfg['initial']['path'],map_location='cpu',weights_only=True)['state_dict']
    checked = {}
    for arm in ('local','mixed'):
        path = root/'formal'/arm
        saved = torch.load(path/'resume.pt',map_location='cpu',weights_only=True)
        adapter = torch.load(path/'adapter.pt',map_location='cpu',weights_only=True)
        exact(saved['adapter'],adapter)
        exact(adapter,torch.load(path/'checkpoints/adapter_000400.pt',map_location='cpu',weights_only=True))
        if not all(k in saved for k in ('rng_cpu','rng_cuda','rng_python')): raise ValueError('missing RNG')
        for state in saved['optimizer']['state'].values():
            if not all(torch.isfinite(v).all() for v in state.values() if isinstance(v,torch.Tensor)):
                raise ValueError('nonfinite AdamW state')
        changed = sum(not torch.equal(t,initial[k]) for k,t in adapter['state_dict'].items())
        if changed!=82: raise ValueError('expected all 82 LoRA tensors updated')
        arm_done = read(path/'complete.json')
        if digest(path/'adapter.pt')!=arm_done['adapter_sha256']: raise ValueError('adapter receipt differs')
        journal = rows(path/'steps.jsonl')
        if dict(Counter(r['dataset'] for r in journal)) != {'REDS':300,'UVG':100}:
            raise ValueError('dataset sampling changed')
        expected = {'256':400} if arm=='local' else {'256':100,'512':300}
        if dict(Counter(str(r['crop'][2]) for r in journal)) != expected: raise ValueError('FOV sampling changed')
        checked[arm] = dict(changed_tensors=changed,optimizer_states=len(saved['optimizer']['state']),
                           steps=saved['step'],**{k:arm_done[k] for k in ('seconds','peak_cuda_allocated_bytes','size_steps','dataset_steps')})
    result = paired_audit(root/'formal',{a:root/'formal'/a for a in ('local','mixed')},400)
    if result!=read(root/'formal/paired_audit.json'): raise ValueError('paired audit differs')
    smoke = root/'smoke'
    verify_artifacts(smoke,read(smoke/'complete.json')['artifacts'])
    for arm in ('local','mixed'):
        exact(*(torch.load(smoke/mode/arm/'resume.pt',map_location='cpu',weights_only=True)
                for mode in ('direct','resumed')))
    smoke_done, final_done = verify_evaluation(smoke/'evaluation'), verify_evaluation(root/'evaluation')
    if smoke_done['new_points']!=8 or final_done['new_points']!=60 or final_done['reused_initial_points']!=30:
        raise ValueError('wrong evaluation cardinality')
    for item in read(smoke/'evaluation/summary.json')['cases']:
        if not all(r['reload_repeat_exact'] for r in item['results'] if r['name']!='initial'):
            raise ValueError('missing actual reload check')
    probe = {i['case']['sample_id']:i for i in read(root.parent/'probe/summary.json')['cases']}
    for item in read(root/'evaluation/summary.json')['cases']:
        reference = {r['size']:r for r in probe[item['case']['sample_id']]['results']
                     if r['name']=='phase2000' and r['seed_index']==0}
        for row in item['results']:
            if row['name']=='initial': continue
            for key in ('condition','noise'):
                if row['observation'][key]!=reference[row['size']]['observation'][key]:
                    raise ValueError('inference conditions/noise not paired')
            if row!=read(Path(row['output_path']).parent/'result.json'):
                raise ValueError('point metadata differs from summary')
    return dict(complete=True,arms=checked,paired_audit=result,new_outputs=60,reused_references=30,
                exact_smoke_both_arms=True,reload_repeat_checks=8,production_changed=False,utc=now())


def chart(output, aggregate, pairs):
    plt = plotting()
    fig,axes = plt.subplots(2,3,figsize=(12,7),layout='constrained')
    for i,(dataset,label) in enumerate((('REDS','REDS / 9 locations'),('UVG','HoneyBee / 3 crops'))):
        for j,(key,title) in enumerate((('lpips','LPIPS (lower)'),('psnr','PSNR dB (higher)'),('phase','Periodic error (diagnostic, lower)'))):
            for size in (256,512):
                row = next(r for r in aggregate if r['group']=='internal_validation' and r['dataset']==dataset and r['size']==size)
                axes[i,j].plot(range(3),[row[n][key] for n in NAMES],'o-',label=f'{size}px inference')
            axes[i,j].set_xticks(range(3),['Initial 2000','Local +400','Mixed +400'])
            axes[i,j].set_title(label+'\n'+title);axes[i,j].grid(alpha=.25);axes[i,j].legend(fontsize=8)
    fig.suptitle('Training recipes / same 128px score core / previously used internal locations / NOT RD')
    fig.savefig(output/'summary.png',dpi=150);plt.close(fig)
    selected = [r for r in pairs if r['size']==512]
    fig,axes = plt.subplots(1,2,figsize=(13,7),layout='constrained')
    labels = [r['sample'].replace('-f000-n17-fullview','').replace('-historical-evaluation-crop','') for r in selected]
    for ax,key in zip(axes,('lpips','phase')):
        delta = [r['mixed_minus_local'][key] for r in selected]
        ax.barh(labels,delta,color=['#087e8b' if d<0 else '#d67730' for d in delta])
        ax.axvline(0,color='black',linewidth=.8);ax.invert_yaxis();ax.grid(axis='x',alpha=.2)
        ax.set_title(key+' : mixed minus local / same 512 input\nnegative = lower; phase is not a quality score')
    fig.savefig(output/'paired_deltas.png',dpi=140);plt.close(fig)


def pictures(output, item, old, probe):
    case,geo = item['case'],item['geometry']
    source,received = full_inputs(case)
    legacy = next(r for r in old['results'] if r['name']=='legacy' and r['size']==512 and r['seed_index']==0)
    with np.load(probe/legacy['relative_dir']/'output.npz') as z: old_pixels=z['pixels'].copy()
    panels = [('Source',rgb_crop(source,geo['large'])),('Received Y',rgb_crop(received,geo['large'])),('Legacy LoRA',old_pixels)]
    temporal=[]
    for row in item['results']:
        with np.load(row['output_path']) as z: pixels=z['pixels'].copy()
        if row['size']==512: panels.append((dict(initial='Initial phase2000',local='Local +400',mixed='Mixed +400')[row['name']],pixels))
        value=local_core(pixels,row['crop'],geo['core'])
        phase=temporal_phase(value,rgb_crop(source,geo['core']))
        if 'temporal_phase' in row:
            for k in phase:
                if not np.isclose(phase[k],row['temporal_phase'][k],rtol=1e-6,atol=1e-6):
                    raise ValueError('temporal diagnostic differs')
        temporal.append(dict(sample=case['sample_id'],group=case['evaluation_group'],dataset=case['dataset'],
                             name=row['name'],size=row['size'],**phase))
    plt=plotting();fig,axes=plt.subplots(2,3,figsize=(13,9),layout='constrained')
    for ax,(name,pixels) in zip(axes.flat,panels):
        ax.imshow(pixels[8],interpolation='nearest');ax.set_title(name);ax.axis('off')
    fig.suptitle(case['sample_id']+'\nWhole 512 processing view / frame 9 / raw G, no fusion / NOT full-system RD',fontsize=11)
    fig.savefig(output/(case['sample_id']+'.png'),dpi=130);plt.close(fig)
    if case['evaluation_group']=='known_artifact': preview(output/(case['sample_id']+'.mp4'),panels)
    return temporal


def preview(path,panels):
    """All 17 real frames at 4fps for inspection; compressed display is not scored."""
    from PIL import Image, ImageDraw
    tmp=path.with_name(path.stem+'.partial.mp4')
    command=['ffmpeg','-hide_banner','-loglevel','error','-y','-f','rawvideo','-pix_fmt','rgb24',
             '-s','1536x1096','-r','4','-i','pipe:0','-an','-c:v','libx264','-threads','2',
             '-crf','18','-pix_fmt','yuv420p','-movflags','+faststart',str(tmp)]
    with subprocess.Popen(command,stdin=subprocess.PIPE) as child:
        try:
            for t in range(17):
                canvas=Image.new('RGB',(1536,1096),'white');draw=ImageDraw.Draw(canvas)
                for i,(name,pixels) in enumerate(panels):
                    x,y=(i%3)*512,(i//3)*548
                    canvas.paste(Image.fromarray(pixels[t]),(x,y+36))
                    draw.text((x+8,y+7),f'{name} / frame {t+1} / 4fps SLOW PREVIEW',fill='black')
                child.stdin.write(canvas.tobytes())
        finally: child.stdin.close()
        if child.wait()!=0: raise RuntimeError('preview encoding failed')
    tmp.replace(path)


def resources(root,audit_result):
    events=rows(root/'heartbeat.jsonl');memory=rows(root/'memory.jsonl')
    gpu=[float(r['gpu'].splitlines()[0].split(',')[2])/1024 for r in events]
    return dict(arms=audit_result['arms'],formal_queue_minutes=events[-1]['elapsed_seconds']/60,
        completed_utc=events[-1]['utc'],sampled_device_peak_gib=max(gpu),
        cgroup_peak_rss_gib=max(r['rss'] for r in memory)/1024**3,
        cgroup_peak_charged_gib=max(r['charged'] for r in memory)/1024**3,
        cgroup_failcnt_first=memory[0]['failcnt'],cgroup_failcnt_last=memory[-1]['failcnt'],
        note='cgroup includes cache and other container processes; failcnt is not an OOM-kill count',
        run_logical_bytes=sum(p.stat().st_size for p in root.parent.rglob('*') if p.is_file()),
        current_disks=disk_snapshot())


def main(args):
    if not os.environ.get('TMUX'): raise RuntimeError('tmux required')
    torch.set_num_threads(4)
    root,output=args.root,args.output or args.root/'report_20261015'
    if output.resolve().is_relative_to(root/'formal') or output.resolve().is_relative_to(root/'evaluation'):
        raise ValueError('keep report outside immutable measurement trees')
    output.mkdir(parents=True,exist_ok=True)
    inputs={str(p):digest(p) for p in (root/'complete.json',root/'evaluation/summary.json',
        root.parent/'probe/summary.json',Path(__file__),root/'heartbeat.jsonl',root/'memory.jsonl')}
    immutable(output/'protocol.json',dict(inputs=inputs,scope='completion audit and saved-pixel report; no inference/training'))
    if (output/'complete.json').exists():
        done=read(output/'complete.json');verify_artifacts(output,done['artifacts'])
        for path,sha in done['input_artifacts'].items():
            if digest(path)!=sha: raise ValueError('input changed: '+path)
        print(json.dumps(dict(complete=True,read_only_reentry=True)),flush=True);return
    began=time.monotonic();checked=audit(root);atomic_json(output/'audit.json',checked)
    print('COMPLETION_AUDIT_PASSED',flush=True)
    summary=read(root/'evaluation/summary.json');pairs=compare_cases(summary['cases']);aggregate=grouped(pairs)
    chart(output,aggregate,pairs)
    old={i['case']['sample_id']:i for i in read(root.parent/'probe/summary.json')['cases']};temporal=[]
    for item in summary['cases']:
        temporal+=pictures(output,item,old[item['case']['sample_id']],root.parent/'probe')
        print('FIGURE_COMPLETE',item['case']['sample_id'],flush=True)
    resource=resources(root,checked)
    atomic_json(output/'summary.json',dict(pairs=pairs,aggregate=aggregate,temporal_phase=temporal,
        resources=resource,scope='same 128px core; input AND supervised FOV changed; no independent-test or RD claim'))
    for p in (root/'formal').rglob('*'):
        if p.is_file():inputs[str(p)]=digest(p)
    for item in summary['cases']:
        for row in item['results']: inputs[row['output_path']]=row['output_sha256']
    names=[p for p in output.iterdir() if p.is_file() and p.name!='complete.json']
    atomic_json(output/'complete.json',dict(complete=True,utc=now(),seconds=time.monotonic()-began,
        input_artifacts=inputs,artifacts={p.name:digest(p) for p in names},training_or_inference=False))
    print(json.dumps(dict(complete=True,groups=aggregate,resources=resource)),flush=True)


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root',type=Path,default=DEFAULT/'training')
    parser.add_argument('--output',type=Path)
    main(parser.parse_args())
